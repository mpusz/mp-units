"""ProperDocs hook that keeps `properdocs serve` responsive.

The two generated references, the API reference (`scripts/mrdocs/run.py`) and the systems
reference (`scripts/systems_reference.py`), are generated from the headers. During a build they
are generated by their own hooks. While serving, that would make every rebuild wait for MrDocs,
about a minute, even when an edit changes nothing the reference shows. So while serving:

1. Their hooks skip generation, and a worker thread started here regenerates them in the
   background whenever a header they depend on changes. Both write only the pages whose content
   changed, so an edit that leaves the output identical touches nothing the server watches, and
   the server does not rebuild at all. A real change produces exactly one rebuild.
2. The file watcher ignores events that cannot change the site. watchdog reports a file opened
   only for reading, and ProperDocs rebuilds the whole site on any event, so grep, an editor or
   this worker reading `docs/` caused rebuilds. A dotfile is never part of the site either, so
   the generators' `.cache.json` files and `docs/.index.md` are ignored too.
"""

from __future__ import annotations

import importlib.util
import threading
from pathlib import Path

import watchdog.events

POLL_SECONDS = 2.0

_serving = False
_stop = threading.Event()
_worker: threading.Thread | None = None


def _load(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _ignore_events_that_cannot_change_the_site() -> None:
    handler = watchdog.events.FileSystemEventHandler
    if getattr(handler.dispatch, "_mp_units_filtered", False):
        return
    original = handler.dispatch
    read_only = (
        watchdog.events.FileOpenedEvent,
        watchdog.events.FileClosedNoWriteEvent,
    )

    def dispatch(self, event):
        if isinstance(event, read_only):
            return
        paths = [event.src_path, getattr(event, "dest_path", "")]
        if all(Path(str(p)).name.startswith(".") for p in paths if p):
            return
        original(self, event)

    dispatch._mp_units_filtered = True
    handler.dispatch = dispatch


class _Script:
    """A generator script, loaded again whenever its file changes.

    A server runs for hours while the scripts are edited, and a stale copy would keep
    regenerating the reference with the old behavior, overwriting what the new one produced.
    """

    def __init__(self, path: Path, name: str):
        self.path, self.name, self.mtime, self.module = path, name, None, None

    def get(self):
        mtime = self.path.stat().st_mtime
        if mtime != self.mtime:
            self.module, self.mtime = _load(self.path, self.name), mtime
        return self.module


def _regenerate_in_background(root: Path) -> None:
    api = _Script(root / "scripts" / "mrdocs" / "run.py", "mp_units_docs_serve_mrdocs")
    systems = _Script(
        root / "scripts" / "systems_reference.py", "mp_units_docs_serve_systems"
    )
    systems_cache = root / "docs" / "reference" / "systems_reference" / ".cache.json"
    while not _stop.wait(POLL_SECONDS):
        try:
            if systems.get().should_regenerate(root, systems_cache)[0]:
                systems.get().generate_if_needed(root)
            if api.get()._input_hash() != api.get()._cached().get("input_hash"):
                api.get().generate_if_needed()
        # a failed regeneration must not take the server down
        except Exception as error:
            print(f"WARNING -  docs_serve: regenerating a reference failed: {error}")


def on_startup(*, command: str, dirty: bool) -> None:
    global _serving
    _serving = command == "serve"
    if _serving:
        _ignore_events_that_cannot_change_the_site()


def on_serve(server, config, builder, **kwargs):
    global _worker
    if _worker is None:
        root = Path(config["docs_dir"]).parent
        _worker = threading.Thread(
            target=_regenerate_in_background,
            args=(root,),
            name="docs_serve",
            daemon=True,
        )
        _worker.start()
    return server


def on_shutdown() -> None:
    _stop.set()
